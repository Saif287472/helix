"""Write screens.json and INTERACTIONS.md: every screen state and what it does.

The prototype must be running (python serve.py). Headless Chrome opens
?manifest, which prints the index as JSON.

screens.json has:
  screens       every screen state: key (the part after # in the address),
                group, label, screen, parameters, the screens underneath it
                (base) and where it opens on a window (placement)
  screenDefs    each screen once: title, placement and its interactions
  interactions  global (the app frame) and components (the page kit)
INTERACTIONS.md is the same interactions as a checklist for the Flutter port.

The run fails when a screen has no interactions list, or uses a gesture
outside GESTURES. A screen with nothing to do declares an empty list.

  python tools/manifest.py
"""
import html
import json
import os
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
from shoot import browser  # noqa: E402

GESTURES = {'tap', 'long-press', 'right-click', 'swipe-left', 'swipe-right', 'swipe', 'drag', 'hold', 'type', 'key', 'scroll', 'auto'}
LAYOUTS = {'phone', 'window'}


def check(data):
    problems = []
    lists = [('global', data['interactions']['global']), ('components', data['interactions']['components'])]
    for sid, d in data['screenDefs'].items():
        if d['interactions'] is None:
            problems.append(f'{sid}: no interactions list (declare [] when it has none)')
        else:
            lists.append((sid, d['interactions']))
    for where, items in lists:
        for it in items:
            if it['gesture'] not in GESTURES:
                problems.append(f"{where}: unknown gesture {it['gesture']!r}")
            if 'only' in it and it['only'] not in LAYOUTS:
                problems.append(f"{where}: unknown layout {it['only']!r}")
    return problems


def checklist(data):
    def line(it):
        only = f" *({it['only']} only)*" if 'only' in it else ''
        return f"- [ ] **{it['gesture']}** {it['on']}: {it['does']}{only}"
    states = {}
    for s in data['screens']:
        states.setdefault(s['screen'], []).append(s['key'])
    out = ['# Orbit interactions', '',
           'GENERATED by `tools/manifest.py` from the prototype. Do not edit by hand:',
           'change the `interactions` list next to the screen in `js/screens/*.js`, the',
           'app frame\'s list in `js/app.js`, or the kit\'s list in `js/kit.js`.', '',
           'Each item is a behaviour the Flutter port must have. Tick it when its',
           'widget test passes. Gestures: ' + ', '.join(sorted(GESTURES)) + '.', '',
           '## Every screen (the app frame)', '', *map(line, data['interactions']['global']), '',
           '## Every page part (the kit)', '', *map(line, data['interactions']['components']), '']
    groups = {}
    for sid, d in data['screenDefs'].items():
        groups.setdefault(d['group'] or 'Other', []).append((sid, d))
    for g, items in groups.items():
        out += [f'## {g}', '']
        for sid, d in items:
            keys = ', '.join(f'`{k}`' for k in states.get(sid, []))
            out += [f"### {d['title']} (`{sid}`, opens: {d['placement']})", '', f'States: {keys}', '']
            out += [line(it) for it in d['interactions']] or ['Nothing to do here beyond reading and the back arrow.']
            out.append('')
    return '\n'.join(out)


def main():
    base = sys.argv[1] if len(sys.argv) > 1 else 'http://127.0.0.1:5317'
    m = None
    for _ in range(3):  # a fresh headless profile sometimes returns before the page runs
        with tempfile.TemporaryDirectory() as tmp:
            out = subprocess.run([browser(), '--headless=new', '--disable-gpu', f'--user-data-dir={tmp}',
                                  '--virtual-time-budget=4000', '--dump-dom', f'{base}/?manifest'],
                                 capture_output=True, text=True, encoding='utf-8', timeout=90).stdout
        m = re.search(r'<pre id="manifest">(.*?)</pre>', out, re.S)
        if m:
            break
    if not m:
        sys.exit('No manifest in the page. Is the prototype running?')
    data = json.loads(html.unescape(m.group(1)))
    problems = check(data)
    if problems:
        sys.exit('Interactions are incomplete:\n  ' + '\n  '.join(problems))
    with open(os.path.join(ROOT, 'screens.json'), 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
        f.write('\n')
    with open(os.path.join(ROOT, 'INTERACTIONS.md'), 'w', encoding='utf-8') as f:
        f.write(checklist(data) + '\n')
    groups = {s['group'] for s in data['screens']}
    n = sum(len(d['interactions']) for d in data['screenDefs'].values())
    g = len(data['interactions']['global']) + len(data['interactions']['components'])
    print(f"{len(data['screens'])} screen states in {len(groups)} groups, {len(data['screenDefs'])} screens, "
          f"{n} screen interactions + {g} shared -> screens.json, INTERACTIONS.md")


if __name__ == '__main__':
    main()
