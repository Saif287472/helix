"""Write the preview app's screen index from the prototype's screens.json.

    python orbit/flutter/tools/gen_screen_index.py [--check]

It reads `orbit/prototype/screens.json` - the manifest
`orbit/prototype/tools/manifest.py` writes from the prototype's own index -
and writes `orbit/flutter/apps/orbit_preview/lib/index.dart`: every screen
state, with the prototype's own key, in the prototype's order.

The Dart file is GENERATED. Never edit it by hand: change the prototype, re-run
`tools/manifest.py`, then run this again. The keys are the contract between the
HTML viewer and the Flutter twin - the compare tool looks the same key up on
both sides - so nothing here is normalised, re-cased or tidied.

The script refuses to write anything it does not understand:

  - a shape in screens.json that this script does not know;
  - a duplicate key, which would make the preview's lookup silently lose one
    of the two screens.

Every run re-reads what it wrote and checks it against screens.json: the same
keys in the same order, with the same labels, groups, screen ids, placements
and parameters, and the file re-reads as UTF-8 exactly as written. `--check`
does that without writing and fails when the file on disk is not what this
script would write, which is the form a CI step wants.
"""
import argparse
import io
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
FLUTTER = os.path.dirname(HERE)               # orbit/flutter
ORBIT = os.path.dirname(FLUTTER)              # orbit
SOURCE = os.path.join(ORBIT, 'prototype', 'screens.json')
OUTPUT = os.path.join(FLUTTER, 'apps', 'orbit_preview', 'lib', 'index.dart')

# What one entry of screens.json's `screens` holds. `base` (the screens
# underneath) is checked but not emitted: nothing in the preview shell needs
# it yet, and a field nobody asked for is a field nobody tests.
SCREEN_FIELDS = ('key', 'group', 'label', 'screen', 'placement', 'params', 'base')
TEXT_FIELDS = ('key', 'group', 'label', 'screen', 'placement')

# dart format's default width. Long parameter texts cannot be broken (a string
# literal is one token), so the generator says how many lines are over it
# instead of pretending.
MAX_WIDTH = 80

_ESCAPES = {'\\': '\\\\', "'": "\\'", '$': '\\$', '\n': '\\n', '\r': '\\r', '\t': '\\t'}
_UNESCAPES = {'\\': '\\', "'": "'", '$': '$', 'n': '\n', 'r': '\r', 't': '\t'}


class ManifestError(Exception):
    """screens.json says something this script will not guess about."""


def fail(message):
    raise ManifestError(message)


# ---------------------------------------------------------------- the Dart text

def dart_string(value):
    """A Dart string literal for `value`, escaped and single quoted."""
    return "'" + ''.join(_ESCAPES.get(ch, ch) for ch in value) + "'"


def pad(width):
    return ' ' * width


def named_argument(name, value, indent):
    """`name: value,` at `indent`, or the value on the next line when long."""
    one_line = pad(indent) + name + ': ' + value + ','
    if len(one_line) <= MAX_WIDTH:
        return [one_line]
    return [pad(indent) + name + ':', pad(indent + 4) + value + ',']


def param_expression(value):
    """The `ScreenParam` for one parameter value."""
    if isinstance(value, bool):                 # bool before int: bool is an int
        return 'ScreenParamFlag(isOn: %s)' % ('true' if value else 'false')
    if isinstance(value, str):
        return 'ScreenParamText(%s)' % dart_string(value)
    if isinstance(value, int):
        return 'ScreenParamNumber(%d)' % value
    return 'ScreenParamItems(<String>[%s])' % ', '.join(
        dart_string(item) for item in value)


def screen_entry(screen, indent):
    """One `ScreenState(...)` entry of `orbitScreens`."""
    lines = [pad(indent) + 'ScreenState(']
    for field in TEXT_FIELDS:
        lines += named_argument(field, dart_string(screen[field]), indent + 2)
    params = screen['params']
    if params:
        lines.append(pad(indent + 2) + 'params: <String, ScreenParam>{')
        for name, value in params.items():
            lines += named_argument(dart_string(name),
                                    param_expression(value), indent + 4)
        lines.append(pad(indent + 2) + '},')
    lines.append(pad(indent) + '),')
    return lines


HEADER = r'''// GENERATED by tools/gen_screen_index.py from orbit/prototype/screens.json
// (written there by prototype/tools/manifest.py). Do not edit this file by
// hand: change the prototype, re-run the manifest, then run the generator.
//
//   python orbit/prototype/tools/manifest.py
//   python orbit/flutter/tools/gen_screen_index.py
//
// The keys, labels, groups and parameters below are the prototype's own, byte
// for byte, because the compare tool looks up the same key on both sides.
//'''


TEMPLATE_TYPES = r'''
/// One parameter of a [ScreenState], exactly as screens.json has it.
///
/// The prototype's parameters are not all text: flags (`empty`, `searching`),
/// numbers (`i`, `n`, `p`) and lists of ids (`sel`, `outputs`) are here too.
/// They are separate types rather than a `dynamic` map, so the file needs no
/// package and the compiler can still check every read.
sealed class ScreenParam {
  const ScreenParam();

  /// The text of a text parameter, or null for any other kind.
  String? get text => null;

  /// Whether a flag is on, or null for any other kind.
  bool? get flag => null;

  /// The number of a number parameter, or null for any other kind.
  int? get number => null;

  /// The items of a list parameter, or null for any other kind.
  List<String>? get items => null;
}

/// A text parameter: a string in screens.json.
final class ScreenParamText extends ScreenParam {
  const ScreenParamText(this.value);

  /// The text, exactly as screens.json has it.
  final String value;

  @override
  String? get text => value;

  @override
  bool operator ==(Object other) =>
      other is ScreenParamText && other.value == value;

  @override
  int get hashCode => Object.hash(ScreenParamText, value);

  @override
  String toString() => 'ScreenParamText($value)';
}

/// A flag parameter, `true` or `false` in screens.json.
final class ScreenParamFlag extends ScreenParam {
  const ScreenParamFlag({required this.isOn});

  /// Whether the flag is on.
  final bool isOn;

  @override
  bool? get flag => isOn;

  @override
  bool operator ==(Object other) =>
      other is ScreenParamFlag && other.isOn == isOn;

  @override
  int get hashCode => Object.hash(ScreenParamFlag, isOn);

  @override
  String toString() => 'ScreenParamFlag(isOn: $isOn)';
}

/// A number parameter, such as the message index `i` or the step `p`.
final class ScreenParamNumber extends ScreenParam {
  const ScreenParamNumber(this.value);

  /// The number, exactly as screens.json has it.
  final int value;

  @override
  int? get number => value;

  @override
  bool operator ==(Object other) =>
      other is ScreenParamNumber && other.value == value;

  @override
  int get hashCode => Object.hash(ScreenParamNumber, value);

  @override
  String toString() => 'ScreenParamNumber($value)';
}

/// A list parameter, such as the picked members `sel` or the call outputs.
final class ScreenParamItems extends ScreenParam {
  const ScreenParamItems(this.values);

  /// The items, in screens.json's order.
  final List<String> values;

  @override
  List<String>? get items => values;

  @override
  bool operator ==(Object other) =>
      other is ScreenParamItems && _sameStrings(other.values, values);

  @override
  int get hashCode => Object.hash(ScreenParamItems, Object.hashAll(values));

  @override
  String toString() => 'ScreenParamItems($values)';
}

/// One screen state of the prototype: the key the compare tool looks up, the
/// label the preview's panel shows, and the parameters that draw it.
final class ScreenState {
  const ScreenState({
    required this.key,
    required this.group,
    required this.label,
    required this.screen,
    required this.placement,
    this.params = const <String, ScreenParam>{},
  });

  /// The prototype's key: the part after `#` in its address.
  final String key;

  /// The panel's group, exactly as screens.json has it.
  final String group;

  /// The label the panel shows, exactly as screens.json has it.
  final String label;

  /// The screen this state draws: `signin`, `chat`, `call`, `state-kit`, ...
  final String screen;

  /// Where the state opens on a window, exactly as screens.json has it.
  ///
  /// `full` takes the window, `list`, `detail` and `info` name a pane, and
  /// `inherit` means the prototype takes the pane of the screen underneath
  /// (see the placement rule in `prototype/js/app.js`). screens.json leaves
  /// `inherit` unresolved, so this file does not invent a pane for it.
  final String placement;

  /// The parameters that draw this state, in screens.json's order.
  final Map<String, ScreenParam> params;

  /// The text of [name], or null when it is missing or not text.
  String? text(String name) => params[name]?.text;

  /// Whether the flag [name] is on. False when it is missing.
  bool flag(String name) => params[name]?.flag ?? false;

  /// The number of [name], or null when it is missing or not a number.
  int? number(String name) => params[name]?.number;

  /// The items of [name], empty when it is missing or not a list.
  List<String> items(String name) => params[name]?.items ?? const <String>[];

  @override
  bool operator ==(Object other) =>
      other is ScreenState &&
      other.key == key &&
      other.group == group &&
      other.label == label &&
      other.screen == screen &&
      other.placement == placement &&
      _sameParams(other.params, params);

  @override
  int get hashCode =>
      Object.hash(key, group, label, screen, placement, _paramsHash(params));

  @override
  String toString() => 'ScreenState($key, $label)';
}

bool _sameStrings(List<String> a, List<String> b) {
  if (identical(a, b)) {
    return true;
  }
  if (a.length != b.length) {
    return false;
  }
  for (var i = 0; i < a.length; i++) {
    if (a[i] != b[i]) {
      return false;
    }
  }
  return true;
}

bool _sameParams(Map<String, ScreenParam> a, Map<String, ScreenParam> b) {
  if (identical(a, b)) {
    return true;
  }
  if (a.length != b.length) {
    return false;
  }
  for (final MapEntry(key: name, value: value) in a.entries) {
    if (b[name] != value) {
      return false;
    }
  }
  return true;
}

/// Unordered, so two equal maps with the same pairs in another order still
/// hash the same.
int _paramsHash(Map<String, ScreenParam> params) {
  return Object.hashAllUnordered(<Object>[
    for (final MapEntry(key: name, value: value) in params.entries)
      Object.hash(name, value),
  ]);
}
'''


TEMPLATE_LOOKUPS = r'''
/// The screen with [key], or null when the prototype has no such key.
ScreenState? orbitScreen(String key) => orbitScreensByKey[key];

/// The screens in [group], in [orbitScreens]' order.
List<ScreenState> orbitScreensInGroup(String group) => orbitScreens
    .where((ScreenState screen) => screen.group == group)
    .toList(growable: false);

/// [orbitScreens] by key, built on first use. Keys are unique: the generator
/// refuses to write a file with two screens of one key.
///
/// A `final` and not a `const`, because a const map literal cannot name the
/// entries of another const collection without repeating every one of them.
final Map<String, ScreenState> orbitScreensByKey = Map<String, ScreenState>.unmodifiable(
  <String, ScreenState>{
    for (final ScreenState screen in orbitScreens) screen.key: screen,
  },
);
'''


def build(screens, groups):
    """The whole generated file, as a string."""
    lines = HEADER.rstrip('\n').split('\n')
    lines.append('')
    lines.append('/// Every screen state of the prototype, in screens.json\'s order:')
    lines.append('/// %d states in %d groups.' % (len(screens), len(groups)))
    lines.append('///')
    lines.append('/// The key is the prototype\'s own, because the compare tool looks')
    lines.append('/// the same key up on both sides. Group the panel with [orbitGroups]')
    lines.append('/// and [orbitScreensInGroup].')
    lines.append('const List<ScreenState> orbitScreens = <ScreenState>[')
    group = None
    for screen in screens:
        if screen['group'] != group:
            group = screen['group']
            if '\n' in group or '\r' in group:
                fail('a group name has a line break in it: %r' % group)
            lines.append(pad(2) + '// %s' % group)
        lines += screen_entry(screen, 2)
    lines.append('];')
    lines.append('')
    lines.append('/// The groups, in the order they first appear in [orbitScreens].')
    lines.append('const List<String> orbitGroups = <String>[')
    for name in groups:
        lines.append(pad(2) + dart_string(name) + ',')
    lines.append('];')
    lines.append(TEMPLATE_TYPES.rstrip('\n'))
    lines.append('')
    lines.append(TEMPLATE_LOOKUPS.strip('\n'))
    return '\n'.join(lines) + '\n'


# ------------------------------------------------------------ reading it back

_STRING = r"'((?:[^'\\]|\\.)*)'"
_FIELD = re.compile(r"^    (key|group|label|screen|placement): " + _STRING + r",$")
_PARAM_INLINE = re.compile(r"^      " + _STRING + r": (.+),$")
_PARAM_NAME_ONLY = re.compile(r"^      " + _STRING + r":$")
_PARAM_VALUE = re.compile(r"^          (.+),$")
_PARAM_TEXT = re.compile(r"^ScreenParamText\(" + _STRING + r"\)$")
_PARAM_FLAG = re.compile(r"^ScreenParamFlag\(isOn: (true|false)\)$")
_PARAM_NUMBER = re.compile(r"^ScreenParamNumber\((-?\d+)\)$")
_PARAM_ITEMS = re.compile(r"^ScreenParamItems\(<String>\[(.*)\]\)$")
_ANY_STRING = re.compile(_STRING)


def unescape(text):
    out = []
    i = 0
    while i < len(text):
        ch = text[i]
        if ch == '\\' and i + 1 < len(text):
            nxt = text[i + 1]
            if nxt not in _UNESCAPES:
                fail('the generator emitted an escape it cannot read back: \\%s' % nxt)
            out.append(_UNESCAPES[nxt])
            i += 2
        else:
            out.append(ch)
            i += 1
    return ''.join(out)


def parse_param(expression):
    match = _PARAM_TEXT.match(expression)
    if match:
        return unescape(match.group(1))
    match = _PARAM_FLAG.match(expression)
    if match:
        return match.group(1) == 'true'
    match = _PARAM_NUMBER.match(expression)
    if match:
        return int(match.group(1))
    match = _PARAM_ITEMS.match(expression)
    if match:
        return [unescape(item) for item in _ANY_STRING.findall(match.group(1))]
    fail('the generator emitted a parameter it cannot read back: %s' % expression)
    return None


def read_back(text):
    """Parse generated Dart back into the data screens.json holds."""
    lines = text.split('\n')
    screens = []
    index = 0
    while index < len(lines):
        if lines[index] != '  ScreenState(':
            index += 1
            continue
        entry = {}
        params = []
        index += 1
        while lines[index] != '  ),':
            line = lines[index]
            field = _FIELD.match(line)
            if field:
                entry[field.group(1)] = unescape(field.group(2))
                index += 1
            elif line == '    params: <String, ScreenParam>{':
                index += 1
                while lines[index] != '    },':
                    inline = _PARAM_INLINE.match(lines[index])
                    if inline:
                        params.append((unescape(inline.group(1)), parse_param(inline.group(2))))
                        index += 1
                    else:
                        name_only = _PARAM_NAME_ONLY.match(lines[index])
                        if not name_only:
                            fail('read-back cannot follow the parameter on line %d: %r'
                                 % (index + 1, lines[index]))
                        name = unescape(name_only.group(1))
                        index += 1
                        value = _PARAM_VALUE.match(lines[index])
                        if not value:
                            fail('read-back cannot follow the value on line %d: %r'
                                 % (index + 1, lines[index]))
                        params.append((name, parse_param(value.group(1))))
                        index += 1
                index += 1
            else:
                fail('read-back cannot follow the entry on line %d: %r' % (index + 1, line))
        entry['params'] = dict(params)
        screens.append(entry)
        index += 1
    return screens


def groups_of(screens):
    """Group names in the order they first appear."""
    names = []
    for screen in screens:
        if screen['group'] not in names:
            names.append(screen['group'])
    return names


def read_groups(text):
    """Parse the orbitGroups list back out of the generated Dart."""
    lines = text.split('\n')
    names = []
    try:
        start = lines.index('const List<String> orbitGroups = <String>[')
    except ValueError:
        fail('there is no orbitGroups list to read back')
        return names
    for line in lines[start + 1:]:
        if line == '];':
            return names
        item = _ANY_STRING.fullmatch(line.strip().rstrip(','))
        if not item:
            fail('read-back cannot follow orbitGroups: %r' % line)
        names.append(unescape(item.group(1)))
    fail('the orbitGroups list is not closed')
    return names


def verify(text, screens, groups):
    """Check the generated Dart against screens.json. Returns a report."""
    back = read_back(text)
    if len(back) != len(screens):
        fail('read back %d screen states, screens.json has %d' % (len(back), len(screens)))
    for expected, got in zip(screens, back):
        for field in TEXT_FIELDS:
            if got.get(field) != expected[field]:
                fail('%s: read back %s=%r, screens.json has %r'
                     % (expected['key'], field, got.get(field), expected[field]))
        if got['params'] != expected['params']:
            fail('%s: read back params %r, screens.json has %r'
                 % (expected['key'], got['params'], expected['params']))
    if groups_of(back) != groups:
        fail('read back the groups %r, screens.json has %r' % (groups_of(back), groups))
    if read_groups(text) != groups:
        fail('orbitGroups holds %r, screens.json has %r' % (read_groups(text), groups))
    long_lines = [n for n, line in enumerate(text.split('\n'), 1) if len(line) > MAX_WIDTH]
    return {
        'screens': len(screens),
        'groups': len(groups),
        'screens_ids': len({screen['screen'] for screen in screens}),
        'parameters': sum(len(screen['params']) for screen in screens),
        'long_lines': long_lines,
    }


# ------------------------------------------------------------- reading the JSON

def check_params(params, where):
    if not isinstance(params, dict):
        fail('%s: params is %s, not an object' % (where, type(params).__name__))
    for name, value in params.items():
        if not isinstance(name, str) or not name:
            fail('%s: a parameter name is not a non-empty string: %r' % (where, name))
        if isinstance(value, bool):
            continue
        if isinstance(value, str):
            continue
        if isinstance(value, int):
            continue
        if isinstance(value, list) and all(isinstance(item, str) for item in value):
            continue
        fail('%s: parameter %r is %s, which the Dart file has no type for'
             % (where, name, json.dumps(value, ensure_ascii=False)))


def load(source):
    """screens.json, checked shape by shape."""
    with io.open(source, 'r', encoding='utf-8', newline='') as handle:
        data = json.load(handle)
    if not isinstance(data, dict):
        fail('screens.json is %s, not an object' % type(data).__name__)
    for field in ('devices', 'listWidth', 'placement', 'interactions', 'screenDefs', 'screens'):
        if field not in data:
            fail('screens.json has no %s field' % field)
    raw = data['screens']
    if not isinstance(raw, list) or not raw:
        fail('screens.json: screens is %s, not a non-empty list' % type(raw).__name__)

    screens = []
    seen = {}
    for position, entry in enumerate(raw):
        where = 'screens[%d]' % position
        if not isinstance(entry, dict):
            fail('%s is %s, not an object' % (where, type(entry).__name__))
        fields = set(entry)
        unknown = fields - set(SCREEN_FIELDS)
        if unknown:
            fail('%s has the fields %s, which this generator does not know; '
                 'update SCREEN_FIELDS in tools/gen_screen_index.py first'
                 % (where, sorted(unknown)))
        missing = set(SCREEN_FIELDS) - fields
        if missing:
            fail('%s is missing the fields %s' % (where, sorted(missing)))
        for field in TEXT_FIELDS:
            if not isinstance(entry[field], str) or not entry[field]:
                fail('%s: %s is %r, not a non-empty string' % (where, field, entry[field]))
        check_params(entry['params'], where)
        if not isinstance(entry['base'], list):
            fail('%s: base is %s, not a list' % (where, type(entry['base']).__name__))
        key = entry['key']
        if key in seen:
            fail('the key %r is on screens[%d] and screens[%d]; the preview\'s '
                 'lookup by key would silently lose one of them'
                 % (key, seen[key], position))
        seen[key] = position
        screens.append({'key': key, 'group': entry['group'], 'label': entry['label'],
                        'screen': entry['screen'], 'placement': entry['placement'],
                        'params': entry['params']})
    return screens, groups_of(screens)


# ------------------------------------------------------------------------ main

def write(path, text):
    """UTF-8, LF, and a replace rather than a half-written file."""
    temporary = path + '.tmp'
    with io.open(temporary, 'w', encoding='utf-8', newline='\n') as handle:
        handle.write(text)
    os.replace(temporary, path)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--check', action='store_true',
                        help='check the file on disk against screens.json and write nothing')
    args = parser.parse_args(argv)

    try:
        screens, groups = load(SOURCE)
        text = build(screens, groups)
        report = verify(text, screens, groups)

        if args.check:
            if not os.path.exists(OUTPUT):
                print('%s does not exist yet' % OUTPUT)
                return 1
            with io.open(OUTPUT, 'rb') as handle:
                on_disk = handle.read()
            if on_disk != text.encode('utf-8'):
                print('%s is not what this script writes; run it without --check' % OUTPUT)
                return 1
            print('%s is up to date with screens.json' % OUTPUT)
            return 0

        write(OUTPUT, text)
        with io.open(OUTPUT, 'rb') as handle:
            raw = handle.read()
        if raw != text.encode('utf-8'):
            fail('the file on disk does not read back as what was written')
        if b'\r' in raw:
            fail('the file on disk has CR in it; the generator writes LF only')
        text.encode('utf-8').decode('utf-8')
    except ManifestError as problem:
        print('%s: %s' % (os.path.basename(SOURCE), problem))
        print('nothing was written')
        return 1

    print('%d screen states, %d groups, %d screens, %d parameters'
          % (report['screens'], report['groups'], report['screens_ids'],
             report['parameters']))
    print('%d keys read back from the Dart file, all of them, in the same order'
          % len(read_back(text)))
    print('%d line(s) are over %d columns; a Dart string literal is one token'
          % (len(report['long_lines']), MAX_WIDTH))
    print('%s' % os.path.relpath(OUTPUT, FLUTTER))
    return 0


if __name__ == '__main__':
    sys.exit(main())