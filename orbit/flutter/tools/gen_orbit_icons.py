"""Write packages/orbit_ui/lib/src/icons/orbit_icons.dart: every Phosphor icon
the prototype draws, at all five weights.

The prototype picks an icon's weight per call site or, when the call site does
not say, from the theme (prototype/js/ui.js, `icon()`; Bloom, Papyrus and
Terminal draw light, Arcade and Field bold, Mochi duotone). So each icon needs
every weight, and the theme chooses at draw time (`OrbitIcon`).

The names are every `ph-<name>` the prototype uses, collected from its sources.
The code points are read from phosphor_flutter 2.1.0's generated tables in the
pub cache (the package itself does not compile on Flutter 3.44; its fonts are
bundled in orbit_ui/fonts/phosphor/). The four flat weights share code points;
duotone draws a second, faded layer, whose code point comes from the same
tables.

  python orbit/flutter/tools/gen_orbit_icons.py [--check]
"""
import glob
import os
import re
import subprocess
import tempfile
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
FLUTTER = os.path.dirname(HERE)
PROTOTYPE = os.path.join(os.path.dirname(FLUTTER), 'prototype')
# orbit_ui lives in the helix_remote workspace since Part B.
OUT = os.path.join(os.path.dirname(os.path.dirname(FLUTTER)), 'helix_remote', 'packages', 'orbit_ui', 'lib', 'src', 'icons', 'orbit_icons.dart')
PKG = os.path.join(os.path.expanduser('~'), 'AppData', 'Local', 'Pub', 'Cache', 'hosted', 'pub.dev',
                   'phosphor_flutter-2.1.0', 'lib', 'src')

# Classes that look like icons but are not (weights, helpers, animations).
NOT_ICONS = {'fill', 'bold', 'light', 'thin', 'duotone', 'regular', 'spin', 'fw'}


def camel(name):
    parts = name.split('-')
    out = parts[0] + ''.join(p[:1].upper() + p[1:] for p in parts[1:])
    return out


def prototype_names(known):
    """Every `ph-<name>` class, plus every quoted string that names a Phosphor
    icon: the prototype passes most names through variables, arrays and
    ternaries (`on ? 'eye-slash' : 'eye'`), so call-site patterns miss some.
    A few quoted words that are not icons there ('video', 'lock') come along;
    unused constants are tree-shaken, so a superset is the safe side."""
    names = set()
    files = glob.glob(os.path.join(PROTOTYPE, 'js', '**', '*.js'), recursive=True)
    files += [os.path.join(PROTOTYPE, 'index.html')]
    for f in files:
        src = open(f, encoding='utf-8').read()
        names |= set(re.findall(r'\bph-([a-z0-9]+(?:-[a-z0-9]+)*)', src))
        names |= {n for n in re.findall(r"'([a-z][a-z0-9-]*)'", src) if camel(n) in known}
    return sorted(n for n in names if n not in NOT_ICONS)


def table(weight):
    src = open(os.path.join(PKG, f'phosphor_icons_{weight}.dart'), encoding='utf-8').read()
    if weight == 'duotone':
        rows = re.findall(r'static const (\w+) = PhosphorDuotoneIconData\(\s*0x([0-9a-fA-F]+),\s*PhosphorIconData\(\s*0x([0-9a-fA-F]+)', src)
        return {n: (int(a, 16), int(b, 16)) for n, a, b in rows}
    rows = re.findall(r'static const (\w+) = PhosphorFlatIconData\(\s*0x([0-9a-fA-F]+)', src)
    return {n: int(c, 16) for n, c in rows}


def formatted(text):
    """The text as `dart format` leaves it, so the committed file and --check
    agree whether or not someone formats the package."""
    with tempfile.TemporaryDirectory() as d:
        path = os.path.join(d, 'orbit_icons.dart')
        with open(path, 'w', encoding='utf-8', newline='\n') as f:
            f.write(text)
        subprocess.run(['dart', 'format', path], check=True, capture_output=True, shell=os.name == 'nt')
        with open(path, encoding='utf-8') as f:
            return f.read()


def main():
    check = '--check' in sys.argv
    flat = {w: table(w) for w in ['regular', 'light', 'bold', 'fill']}
    duo = table('duotone')
    names = prototype_names(flat['regular'])
    missing = [n for n in names if camel(n) not in flat['regular']]
    names = [n for n in names if camel(n) in flat['regular']]

    def data(cp, family):
        return f"IconData(0x{cp:X}, fontFamily: '{family}', fontPackage: 'orbit_ui')"

    out = ['// GENERATED by tools/gen_orbit_icons.py. Do not edit by hand.', '//',
           '// Every Phosphor icon the prototype draws, at all five weights. Draw one',
           '// with OrbitIcon, which picks the weight the theme or the call site asks for.',
           '', "import 'package:flutter/widgets.dart' show IconData;", '',
           "import 'package:orbit_ui/src/icons/orbit_glyph.dart';", '',
           '/// Every Phosphor icon the Orbit prototype draws, by its prototype name.',
           'abstract final class OrbitIcons {']
    for n in names:
        c = camel(n)
        cps = [flat[w].get(c) for w in ['regular', 'light', 'bold', 'fill']]
        if any(cp is None for cp in cps) or c not in duo:
            missing.append(n + ' (a weight is missing)')
            continue
        d1, d2 = duo[c]
        out += [f'  /// `ph-{n}`.', f'  static const {c} = OrbitGlyph(',
                f"    '{n}',", f"    regular: {data(cps[0], 'PhosphorRegular')},",
                f"    light: {data(cps[1], 'PhosphorLight')},", f"    bold: {data(cps[2], 'PhosphorBold')},",
                f"    fill: {data(cps[3], 'PhosphorFill')},", f"    duotone: {data(d1, 'PhosphorDuotone')},",
                f"    duotoneBack: {data(d2, 'PhosphorDuotone')},", '  );', '']
    out[-1:] = ['}', '']
    text = formatted('\n'.join(out))
    if check:
        same = os.path.exists(OUT) and open(OUT, encoding='utf-8').read() == text
        sys.exit(0 if same else 'orbit_icons.dart is out of date: run tools/gen_orbit_icons.py')
    open(OUT, 'w', encoding='utf-8', newline='\n').write(text)
    print(f'{len(names)} icons -> {OUT}')
    if missing:
        print('Not in Phosphor (check these in the prototype):', ', '.join(missing))


if __name__ == '__main__':
    main()
