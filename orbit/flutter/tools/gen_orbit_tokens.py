"""Write orbit_ui's OrbitTokens from the generated theme JSON.

    python tools/gen_orbit_tokens.py

**Why this is generated.** `OrbitTokens` is the port's `HelixColorTokens`:
every value the prototype's tokens.css defines, as a named Dart field, so a
screen writes `tokens.accent` and never a hex or a CSS string. That is 111
fields across 12 value types, and a single mistyped field name would compile
fine and draw the wrong colour - which is exactly the class of mistake the
byte-identical check catches on the CSS side.

So the fields come from the same JSON the app loads at runtime, and
`test/orbit_tokens_test.dart` asserts the two agree. If a theme gains a token,
this file and the test fail together until it is regenerated: nothing is
silently missing.

The JSON is generated too, by `orbit/prototype/tools/themes.py`, from the one
theme table. This script adds no design decisions of its own.
"""
import io
import json
import os
import subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
# orbit_ui lives in the helix_remote workspace since Part B.
PKG = os.path.join(HERE, '..', '..', '..', 'helix_remote', 'packages', 'orbit_ui')
THEMES = os.path.join(PKG, 'assets', 'themes')
OUT = os.path.join(PKG, 'lib', 'src', 'theme', 'orbit_tokens.g.dart')

# The Dart type of each JSON group.
TYPES = {
    'colour': 'Color',
    'shadow': 'List<BoxShadow>',
    'gradient': 'LinearGradient',
    'gradientRef': 'LinearGradient',
    'fontStack': 'OrbitFontStack',
    'weight': 'int',
    'em': 'double',
    'transform': 'OrbitTextTransform',
    'pattern': 'OrbitPattern',
    'patternSize': 'OrbitTile',
    'lengthPx': 'double',
    'lengthPct': 'double',
}

# `in` is a Dart keyword; a handful of CSS names read better renamed.
RENAME = {'in': 'inBubble', 'read': 'readTick'}


def field_name(key):
    if key in RENAME:
        return RENAME[key]
    out = ''
    upper = False
    for ch in key:
        if ch == '-':
            upper = True
        elif upper:
            out += ch.upper()
            upper = False
        else:
            out += ch
    return out


def main():
    files = sorted(f for f in os.listdir(THEMES) if f.endswith('.json'))
    if not files:
        raise SystemExit('no theme JSON in %s - run prototype/tools/themes.py' % THEMES)

    # Every theme must declare exactly the same tokens, or a widget written
    # against one theme will not compile against another.
    shapes = {}
    for name in files:
        with io.open(os.path.join(THEMES, name), encoding='utf-8') as f:
            doc = json.load(f)
        shapes[name] = {g: sorted(v) for g, v in doc['tokens'].items()}
    first = shapes[files[0]]
    for name, shape in shapes.items():
        if shape != first:
            raise SystemExit('%s declares different tokens from %s' % (name, files[0]))

    groups = sorted(first)
    missing = sorted(set(TYPES) - set(groups))
    if missing:
        raise SystemExit('the JSON has groups with no Dart type: %s' % missing)
    extra = sorted(set(groups) - set(TYPES))
    if extra:
        raise SystemExit('a new group needs a Dart type before this can run: %s' % extra)

    fields = []
    for group in groups:
        for key in first[group]:
            fields.append((group, key, field_name(key)))

    seen = {}
    for _, key, name in fields:
        if name in seen:
            raise SystemExit('two tokens both become %s (%s and %s)'
                             % (name, seen[name], key))
        seen[name] = key

    # The parser keys tokens by their short name, so two groups sharing one
    # would shadow each other at runtime; refuse it here, where the message
    # can name both groups.
    leaves = {}
    for group, key, _ in fields:
        if key in leaves:
            raise SystemExit('token %r appears in both %s and %s; the parser '
                             'keys tokens by leaf name' % (key, leaves[key], group))
        leaves[key] = group

    w = []
    a = w.append
    a('// GENERATED by tools/gen_orbit_tokens.py from the theme JSON that')
    a('// orbit/prototype/tools/themes.py writes. Do not edit by hand: regenerate,')
    a('// and let test/orbit_tokens_test.dart check the two agree.')
    a('//')
    a('// Every field is one value the prototype\'s tokens.css defines. The names')
    a('// follow the CSS custom properties, camel-cased, so a screen reads')
    a('// `tokens.chatBg` where the prototype says `--chat-bg`.')
    a("part of 'orbit_tokens.dart';")
    a('')
    a('/// Every token a theme must carry, spelled `group.key` as the JSON has it.')
    a('///')
    a('/// [OrbitTokens.fromThemeJson] refuses a document that lacks one. A theme')
    a('/// is chosen and saved, so a token found missing at draw time would make')
    a('/// the next launch throw above the router, with no way back in the app.')
    a('const orbitRequiredTokenNames = <String>{')
    for group, key, _ in fields:
        a("  '%s.%s'," % (group, key))
    a('};')
    a('')
    a('/// The typed view of one theme JSON: one getter per token.')
    a('///')
    a('/// Generated as an extension rather than as fields so the class itself can')
    a('/// stay a plain value that [ThemeExtension] can copy and lerp, and so a new')
    a('/// token is a new getter instead of a new constructor argument.')
    a('extension OrbitTokensValues on OrbitTokens {')
    for group in groups:
        a('  // %s' % group)
        for key in first[group]:
            a('  %s get %s => value<%s>(%r);'
              % (TYPES[group], field_name(key), TYPES[group], key))
        a('')
    a('}')
    a('')

    io.open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(w))
    # The helix_remote gate checks formatting, so leave the file as
    # `dart format` would.
    subprocess.run(['dart', 'format', OUT], check=True, shell=os.name == 'nt')
    print('wrote %s: %d tokens in %d groups' % (OUT, len(fields), len(groups)))


if __name__ == '__main__':
    main()