/// Every value a theme carries, read from its JSON file.
///
/// **There is no per-theme constant in Dart.** A theme is data: `themes.py`
/// writes one JSON file per theme from the same table that writes the
/// prototype's CSS, and this loads it. Built-in themes and downloadable theme
/// packs (Part C) therefore share one format, and a pack can only ever bring
/// data - never code, which a release Flutter build could not load anyway.
///
/// Screens read tokens as `Theme.of(context).orbit.accent` (see
/// [OrbitTokens.of]) or through [OrbitTokensValues]: `tokens.accent`,
/// `tokens.chatBg`, `tokens.rMd`. The names follow the prototype's CSS custom
/// properties, camel-cased, so `--chat-bg` is [OrbitTokensValues.chatBg].
///
/// The getters are generated by `tools/gen_orbit_tokens.py` into
/// `orbit_tokens.g.dart`, because there are 111 of them across 12 value types
/// and a mistyped name would compile and draw the wrong colour.
final class OrbitTokens extends ThemeExtension<OrbitTokens> {
  const OrbitTokens._(this._values, this.meta, this.motion);

  /// Builds tokens from one theme JSON document.
  ///
  /// Throws [FormatException] when a token is missing or a value has the wrong
  /// shape, rather than drawing a default: a theme that half-loaded would look
  /// like a design decision, and it would not be one.
  factory OrbitTokens.fromThemeJson(Map<String, Object?> json) {
    final raw = json['tokens'];
    if (raw is! Map) {
      throw FormatException('a theme has no "tokens"', json.toString());
    }
    final effects = _effects(json['effects']);
    final values = <String, Object?>{};

    Object colour(Object? v, String key) {
      if (v is! Map || v['hex'] is! String) {
        throw FormatException('not a colour', '$key: $v');
      }
      final rgb = int.parse(
        'ff${(v['hex']! as String).replaceFirst('#', '')}',
        radix: 16,
      );
      final alpha = v['alpha'];
      if (alpha is! num) {
        throw FormatException('a colour has no alpha', '$key: $v');
      }
      return Color.fromARGB(
        (alpha.toDouble() * 255).round(),
        (rgb >> 16) & 0xff,
        (rgb >> 8) & 0xff,
        rgb & 0xff,
      );
    }

    Object shadows(Object? v, String key) {
      if (v is! List) throw FormatException('not a shadow list', '$key: $v');
      return <BoxShadow>[
        for (final layer in v)
          BoxShadow(
            color: colour(layer is Map ? layer['colour'] : null, key) as Color,
            offset: Offset(_num(layer, 'dx'), _num(layer, 'dy')),
            blurRadius: orbitCssBlur(_num(layer, 'blur')),
            spreadRadius: _num(layer, 'spread'),
          ),
      ];
    }

    Object gradient(Object? v, String key) {
      if (v is! Map) throw FormatException('not a gradient', '$key: $v');
      final stops = v['stops'];
      if (stops is! List) throw FormatException('no stops', '$key: $v');
      final colors = <Color>[];
      final at = <double>[];
      for (final s in stops) {
        if (s is! Map) throw FormatException('a stop is not a map', '$key: $s');
        // A stop either names a colour outright or refers to another token,
        // which is how `--brand-gradient` is built from the call colours. The
        // colours are read first because `values` is filled in JSON order.
        if (s['token'] is String) {
          colors.add(values[s['token']! as String]! as Color);
        } else {
          colors.add(colour(s['colour'], key) as Color);
        }
        at.add(s['at'] is num ? (s['at']! as num).toDouble() : 0);
      }
      return LinearGradient(
        begin: Alignment.topLeft,
        end: Alignment.bottomRight,
        colors: colors,
        stops: at,
      );
    }

    for (final entry in raw.entries) {
      final group = entry.key as String;
      final map = entry.value;
      if (map is! Map) throw FormatException('not a token group', group);
      for (final token in map.entries) {
        final key = '$group.${token.key}';
        final v = token.value;
        values[token.key as String] = switch (group) {
          'colour' => colour(v, key),
          'shadow' => shadows(v, key),
          'gradient' || 'gradientRef' => gradient(v, key),
          'fontStack' => OrbitFontStack._fromJson(v, key),
          'weight' => _int(v, key),
          'em' => _double(v, key),
          'transform' => OrbitTextTransform.values.byName('$v'),
          'pattern' => OrbitPattern._fromJson(v, key),
          'patternSize' => OrbitTile._fromJson(v, key),
          'lengthPx' || 'lengthPct' => _double(v, key),
          _ => throw FormatException('no Dart type for this group', group),
        };
      }
    }
    final meta = _meta(json, effects);
    final pattern = values['chat-pattern'];
    if (pattern is OrbitPattern) {
      OrbitEffects.validate(meta.id, [
        for (final e in effects) e.kind,
      ], pattern.kind);
    }
    final motion = OrbitMotion.fromThemeJson(json);
    return OrbitTokens._(Map.unmodifiable(values), meta, motion);
  }

  static double _num(Object? layer, String field) {
    if (layer is Map && layer[field] is num) {
      return (layer[field]! as num).toDouble();
    }
    return 0;
  }

  /// A plain JSON number. Separate from [_num] because that one reads a field
  /// out of a shadow layer's map, and a token's own value *is* the number.
  static double _double(Object? v, String key) {
    if (v is num) return v.toDouble();
    throw FormatException('not a number', '$key: $v');
  }

  static int _int(Object? v, String key) {
    if (v is int) return v;
    if (v is num) return v.toInt();
    throw FormatException('not a whole number', '$key: $v');
  }

  static OrbitThemeMeta _meta(
    Map<String, Object?> json,
    List<OrbitEffect> effects,
  ) {
    String? str(String k) => json[k] as String?;
    return OrbitThemeMeta(
      id: str('id') ?? '',
      name: str('name') ?? '',
      vibe: str('vibe') ?? '',
      dark: json['dark'] == true,
      icon: str('icon') ?? '',
      effects: effects,
    );
  }

  static List<OrbitEffect> _effects(Object? raw) {
    if (raw == null) return const [];
    if (raw is! List) throw FormatException('effects is not a list', '$raw');
    return [
      for (final e in raw)
        if (e is Map && e['kind'] is String)
          OrbitEffect(
            e['kind']! as String,
            Map.unmodifiable(
              Map<Object?, Object?>.from(e['params'] as Map? ?? const {}),
            ),
          ),
    ];
  }

  final Map<String, Object?> _values;

  /// The theme's identity and its effects: what the picker shows, and what the
  /// effect registry reads to know what this theme switches on.
  final OrbitThemeMeta meta;

  /// How this theme moves.
  final OrbitMotion motion;

  /// One token by its generated name, or by `group.key` as the JSON has it.
  ///
  /// Throws when the token is not in this theme, because a screen that reads a
  /// token no theme defines is a bug in the screen, not a default to invent.
  T value<T>(String name) {
    final v = _values[name];
    if (v == null) {
      throw ArgumentError.value(
        name,
        'name',
        'not a token of this theme; the JSON has ${_values.length}',
      );
    }
    if (v is! T) {
      throw ArgumentError.value(name, 'name', 'is ${v.runtimeType}, not $T');
    }
    return v as T;
  }

  /// Every token, by the JSON's own `group.key` spelling. For tests and tools.
  Map<String, Object?> get values => _values;

  /// The tokens of the context's theme.
  static OrbitTokens of(BuildContext context) =>
      Theme.of(context).extension<OrbitTokens>()!;

  @override
  OrbitTokens copyWith({ThemeExtension<OrbitTokens>? theme}) =>
      theme is OrbitTokens ? theme : this;

  /// Themes cross-fade: colours and lengths interpolate, and everything else -
  /// shadows-as-a-list, patterns, fonts - switches at the halfway point.
  ///
  /// Interpolating a box shadow or a pattern would mean re-solving it against
  /// both themes, and nothing in the prototype cross-fades those; switching is
  /// what a person actually sees when a theme changes.
  @override
  OrbitTokens lerp(covariant OrbitTokens? other, double t) {
    if (other == null || t >= 1) return this;
    if (t <= 0) return other;
    final merged = <String, Object?>{};
    for (final entry in _values.entries) {
      final a = entry.value;
      final b = other._values[entry.key];
      merged[entry.key] = switch ((a, b)) {
        (Color x, Color y) => Color.lerp(x, y, t),
        (double x, double y) => x + (y - x) * t,
        _ => t < 0.5 ? a : b,
      };
    }
    return OrbitTokens._(
      Map.unmodifiable(merged),
      t < 0.5 ? meta : other.meta,
      t < 0.5 ? motion : other.motion,
    );
  }
}

/// A CSS `box-shadow` blur length as Flutter's [BoxShadow.blurRadius]: the
/// same number.
///
/// The two are defined differently on paper, so this is a measurement, not a
/// derivation. On 2026-10-18 the startup screen's logo shadow (`0 16px 40px
/// -18px`) was shot at several factors and compared with Chrome's pixels
/// around it: the mean error was 5.3 colour levels at half the CSS number,
/// 2.1 at 0.85, 2.0 at 1.0 and 4.1 at 1.2. Keep it at 1.0 unless the compare
/// tool shows otherwise.
double orbitCssBlur(double css) => css;

/// Who a theme is, and what it switches on.
final class OrbitThemeMeta {
  const OrbitThemeMeta({
    required this.id,
    required this.name,
    required this.vibe,
    required this.dark,
    required this.icon,
    required this.effects,
  });

  final String id;
  final String name;

  /// The short line the picker shows under the name ("Gaming · neon").
  final String vibe;
  final bool dark;

  /// The Phosphor weight this theme's icons use: regular, fill, bold, light or
  /// duotone, or empty for regular.
  final String icon;

  /// The theme's effects, in the order the prototype draws them. The registry
  /// in `lib/src/theme/effects.dart` reads these by name.
  final List<OrbitEffect> effects;

  bool has(String kind) => effects.any((e) => e.kind == kind);
  OrbitEffect? effect(String kind) {
    for (final e in effects) {
      if (e.kind == kind) return e;
    }
    return null;
  }
}

/// One effect a theme switches on: a name from the fixed registry, and the
/// settings it draws it with.
final class OrbitEffect {
  const OrbitEffect(this.kind, this.params);

  /// `ornament`, `cursor`, `bubbleStripe`, `wordmarkGlow`, ... - one of
  /// [OrbitEffects.kinds]. A name the app does not ship is refused, because
  /// only data is ever downloaded and the effect *types* are in the app.
  final String kind;

  /// The settings, exactly as the theme table records them. Read through
  /// [param], never through a cast at the call site.
  final Map<Object?, Object?> params;

  T? param<T>(String name) {
    final v = params[name];
    return v is T ? v : null;
  }
}

/// A font stack, in the order CSS would try them.
final class OrbitFontStack {
  const OrbitFontStack(this.families);

  factory OrbitFontStack._fromJson(Object? v, String key) {
    if (v is! Map || v['families'] is! List) {
      throw FormatException('not a font stack', '$key: $v');
    }
    return OrbitFontStack([
      for (final f in v['families']! as List)
        if (f is String) f,
    ]);
  }

  final List<String> families;

  /// The first family in the stack this build can draw, by the name Flutter
  /// knows it by (see [OrbitFonts.qualify]), or null for the platform's font.
  ///
  /// The CSS fallback chain (`ui-sans-serif, system-ui, sans-serif`) means
  /// "whatever the platform uses", and a null family means the same thing to
  /// Flutter.
  String? get family {
    for (final f in families) {
      final name = OrbitFonts.qualify(f);
      if (name != null) return name;
    }
    return null;
  }

  /// Text in this stack the way the prototype's CSS sets it.
  ///
  /// - [weight] goes to the `wght` axis as well as [FontWeight]: the bundled
  ///   faces are variable, and Flutter picks a variable face's weight by its
  ///   axis, not by [TextStyle.fontWeight].
  /// - [letterSpacingEm] is CSS `letter-spacing` in `em`.
  /// - [height] is CSS `line-height`; the phone screen's is 1.4. The leading
  ///   is split evenly above and below, as CSS does, so a line sits where the
  ///   browser puts it.
  TextStyle style({
    required double size,
    int weight = 400,
    Color? color,
    double letterSpacingEm = 0,
    double height = 1.4,
  }) => TextStyle(
    fontFamily: family,
    fontSize: size,
    fontWeight: FontWeight.values[((weight ~/ 100) - 1).clamp(0, 8)],
    fontVariations: [FontVariation('wght', weight.toDouble())],
    color: color,
    letterSpacing: letterSpacingEm * size,
    height: height,
    leadingDistribution: TextLeadingDistribution.even,
  );
}

/// `text-transform` in the theme table. CSS allows four; Flutter's
/// [TextStyle] has none, so the screens apply it themselves.
enum OrbitTextTransform { none, uppercase, lowercase, capitalize }

/// A chat pattern: a name from the registry, and its settings.
///
/// Never a picture and never a CSS string - the whole point is that a theme
/// asks for a pattern by name and the app knows how to draw it.
final class OrbitPattern {
  const OrbitPattern(this.kind, this.params);

  factory OrbitPattern._fromJson(Object? v, String key) {
    if (v is! Map || v['kind'] is! String) {
      throw FormatException('not a pattern', '$key: $v');
    }
    return OrbitPattern(
      v['kind']! as String,
      Map.unmodifiable(
        Map<Object?, Object?>.from(v['params'] as Map? ?? const {}),
      ),
    );
  }

  /// `none`, `grain`, `hearts`, `neon-grid`, `scanlines`, `contours`.
  final String kind;
  final Map<Object?, Object?> params;

  bool get isNone => kind == 'none';

  /// The tile the pattern repeats over, or null when it has none (Terminal's
  /// scanlines carry their own period).
  OrbitTile get size => OrbitTile.fromParams(params);

  T? param<T>(String name) {
    final v = params[name];
    return v is T ? v : null;
  }

  /// A pattern colour, which may be a hex or a token name.
  OrbitColour? paramColour(String name) {
    final v = params[name];
    if (v is String && v.startsWith('#')) return OrbitColour.hex(v);
    return null;
  }
}

/// How large a repeated pattern's tile is.
final class OrbitTile {
  const OrbitTile(this.width, this.height);

  static const none = OrbitTile(null, null);

  factory OrbitTile._fromJson(Object? v, String key) {
    if (v is! Map) throw FormatException('not a tile size', '$key: $v');
    if (v['auto'] == true) return none;
    final w = v['w'];
    final h = v['h'];
    if (w is! num || h is! num) {
      throw FormatException('a tile needs a width and a height', '$key: $v');
    }
    return OrbitTile(w.toDouble(), h.toDouble());
  }

  static OrbitTile fromParams(Map<Object?, Object?> params) {
    final s = params['size'];
    if (s == null) return none;
    if (s is List && s.length == 2) {
      final a = s[0];
      final b = s[1];
      if (a is num && b is num) return OrbitTile(a.toDouble(), b.toDouble());
    }
    return none;
  }

  final double? width;
  final double? height;

  bool get isAuto => width == null || height == null;

  /// Flutter's `ImageRepeat` + tile size for this pattern.
  Size? get size => isAuto ? null : Size(width!, height!);
}

/// A colour a theme writes as data rather than as pixels: either a literal hex
/// or the name of another token it reads, which is how the prototype's CSS
/// mixes `var(--accent)` with `#6B7A45`.
final class OrbitColour {
  const OrbitColour._(this.hex, this.token);

  factory OrbitColour.hex(String hex) => OrbitColour._(hex, null);
  factory OrbitColour.token(String token) => OrbitColour._(null, token);

  final String? hex;
  final String? token;

  bool get isToken => token != null;

  /// The value, given the theme that resolves tokens.
  Color resolve(OrbitTokens tokens) {
    final name = token;
    if (name != null) return tokens.value<Color>(name);
    final h = hex!.replaceFirst('#', '');
    final rgb = int.parse('ff$h', radix: 16);
    return Color.fromARGB(
      0xff,
      (rgb >> 16) & 0xff,
      (rgb >> 8) & 0xff,
      rgb & 0xff,
    );
  }
}
