"""Helix Console tokens: the console's theme file, generated from Orbit's table.

    python tools/themes.py        -> writes css/tokens.css, prints a contrast
                                     report (fails loudly on any pair)

The single source of every colour is `orbit/prototype/tools/themes.py`. This
file adds nothing to that palette: it takes the two themes the console can use
(Orbit and Orbit Night), derives the console-only tokens from them, and checks
the result with Orbit's own contrast gate.

Console-only tokens are layout and type, plus four colours that only exist
because a console has a rail and a focus ring. They are defined here, once, so
no screen ever writes a `#` value.

Orbit's `main()` is never called: it writes into `helix_remote/`.
"""
import importlib.util
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'css', 'tokens.css')
ORBIT = os.path.normpath(os.path.join(HERE, '..', '..', '..',
                                      'orbit', 'prototype', 'tools', 'themes.py'))

spec = importlib.util.spec_from_file_location('orbit_themes', ORBIT)
if spec is None or spec.loader is None:
    sys.exit(f'cannot load the Orbit token source at {ORBIT}')
O = importlib.util.module_from_spec(spec)
spec.loader.exec_module(O)

# The console speaks the messenger's themes, by the same ids.
IDS = ('orbit', 'night')

# ------------------------------------------------------- console-only tokens
# Sizes and type steps: the console is one step denser than the phone app, and
# these are the numbers every screen is measured against. Not colours.
LAYOUT = {
    'rail-w': '68px',          # the instrument rail, labels always visible
    'strip-h': '54px',         # the status strip above the content
    'row-h': '34px',           # a list row: one line of facts
    'row-h-table': '34px',     # a table row at the same measure
    'gutter': '20px',          # content padding on a wide window
    'target': '48px',          # the smallest tap target, never below this
    'ring-w': '2px',
    'dur': '180ms',
    'dur-page': '260ms',
    'ease': 'cubic-bezier(.2,.8,.2,1)',
    'tnum': 'tabular-nums',
}

# The type steps are the only tokens that scale: the review mode puts
# `--text-scale: 2` on a subtree and every size below follows, so a screen is
# never tested at one text size only.
TYPE = {
    't-display': '30px',
    't-title': '21px',
    't-headline': '16px',
    't-body': '13.5px',
    't-small': '12.5px',
    't-caption': '11.5px',
    't-meta': '10.5px',
}


def scaled_type(scale):
    """The type block, written twice from one table: once at the reading size
    and once doubled for the 2x review state."""
    out = [f'  --text-scale: {scale};']
    out += [f'  --{n}: calc({v} * var(--text-scale));' for n, v in TYPE.items()]
    out.append('  font-size: var(--t-body);')
    return out


def console_tokens(t, k):
    """The four colours a console needs and the messenger's table has no name
    for - all of them derived, none of them invented."""
    inv, on = k['inverse'], k['on-inverse']
    acc = k['accent']
    return {
        'rail-ink': on,
        'rail-ink-2': O.mix(on, inv, 0.34),
        'rail-ink-3': O.mix(on, inv, 0.52),
        'rail-line': O.mix(inv, on, 0.16),
        'rail-hover': O.mix(inv, on, 0.08),
        'focus': O.fit_ink(acc, k['surface'], t['dark']),
    }


# ------------------------------------------------------------- contrast gate
def check_console(t, k):
    """Orbit's own pairs, plus the console's rail and focus ring."""
    fails = list(O.check(t, k))
    pairs = [
        ('rail-ink / inverse', k['rail-ink'], k['inverse'], 7),
        ('rail-ink-2 / inverse', k['rail-ink-2'], k['inverse'], 4.5),
        ('rail-ink-3 / inverse', k['rail-ink-3'], k['inverse'], 3),
        ('focus / surface', k['focus'], k['surface'], 4.5),
        ('focus / bg', k['focus'], k['bg'], 4.5),
    ]
    for label, a, b, need in pairs:
        r = O.contrast(a, b)
        if r < need:
            fails.append(f'{label} {r:.2f} < {need}')
    return fails


def main():
    path = ORBIT.replace('\\', '/')
    css = [
        '/* GENERATED by console/prototype/tools/themes.py - do not edit.',
        f'   Source of every colour: {path}',
        '   Re-run: python tools/themes.py   (it prints the contrast report)',
        '',
        '   The console uses two themes, by the messenger\'s ids: orbit, night.',
        '   Console-only tokens are layout and type plus four derived colours',
        '   (rail-ink, rail-ink-2, rail-ink-3, rail-line, rail-hover, focus).',
        '   No screen may write a # value.',
        ' */',
    ]
    report, bad = [], 0
    themes = [t for t in O.THEMES if t['id'] in IDS]
    if len(themes) != len(IDS):
        sys.exit(f'Orbit no longer has the themes {IDS}: found '
                 f'{[t["id"] for t in themes]}')
    for t in themes:
        k = O.tokens(t)
        k.update(console_tokens(t, k))
        css.append(f'[data-theme="{t["id"]}"] {{')
        css += [f'  --{n}: {v};' for n, v in k.items()]
        css.append('}')
        rules = O.effects_css(t)
        if rules:
            css.append(rules)
    css.append(':root {')
    css += [f'  --{n}: {v};' for n, v in LAYOUT.items()]
    css += scaled_type('1')
    css.append('}')
    css.append('.text-2x {')
    css += scaled_type('2')
    css.append('}')
    css.append('@media (prefers-reduced-motion: reduce) {\n  :root { --dur: 0ms; --dur-page: 0ms; }\n}')

    for t in themes:
        k = O.tokens(t)
        k.update(console_tokens(t, k))
        fails = check_console(t, k)
        bad += len(fails)
        report.append(f"{t['name']:<12} {'OK' if not fails else 'FAIL'}"
                      + ''.join(f'\n    - {f}' for f in fails))

    out = os.path.normpath(OUT)
    os.makedirs(os.path.dirname(out), exist_ok=True)
    open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(css) + '\n')
    print('\n'.join(report))
    print(f'\n{len(themes)} themes, {len(LAYOUT)} layout + {len(TYPE)} type tokens '
          f'-> css/tokens.css, {bad} contrast failures')
    if bad:
        sys.exit(1)


if __name__ == '__main__':
    main()
